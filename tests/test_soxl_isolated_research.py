def test_development_uses_orchestrator_for_three_trials_without_disk_records(
    snapshot, monkeypatch
):
    module = _module()
    before = {path.name: path.read_bytes() for path in snapshot.iterdir()}
    calls = []
    original_run = module.BacktestOrchestrator.run

    def replay(_self, _start, _end, cost_bps):
        return _fake_window(cost_bps)

    def tracked_run(self, *args, **kwargs):
        result = original_run(self, *args, **kwargs)
        calls.append((args, kwargs, result))
        return result

    monkeypatch.setattr(module.SoxlDevelopmentLearningRunner, "_replay_window", replay)
    monkeypatch.setattr(module.BacktestOrchestrator, "run", tracked_run)
    result = module.run_soxl_isolated_development(snapshot, **_arguments(snapshot))

    assert result["status"] == "development_completed"
    assert result["failure_reason"] is None
    assert result["trial_count_started"] == result["trial_count_completed"] == 3
    assert result["cost_scenario_count_started"] == result["cost_scenario_count_completed"] == 9
    assert result["real_backtest_executed"] is True
    assert len(calls) == 3
    assert all(call[1]["end_date"] == module.DEVELOPMENT_END for call in calls)
    assert all(call[1]["params"]["learning_only"] is True for call in calls)
    assert all(call[2].oos_sharpe is None for call in calls)
    assert all(call[2].oos_calmar is None for call in calls)
