def test_learning_open_stop_uses_open_and_prior_regime_and_rejects_scaling(
    snapshot, monkeypatch
):
    module = _module()
    admission = _preflight(snapshot, monkeypatch)
    runner = module.SoxlDevelopmentLearningRunner(
        json.loads((snapshot / "input.json").read_bytes()),
        admission["runtime_configs"][0],
        source_identity=admission["source_identity"],
        deadline=time.monotonic() + 30.0,
    )
    observed = []

    def approve(_decision, portfolio, *, market_data):
        observed.append((portfolio.total_equity, market_data["market_regime"]))
        return RiskAction(action="approve", reason="bounded")

    runner._risk_engine.assess = approve
    state = runner._initial_state()
    state.quantities["SOXL"] = 1.0
    state.cash -= runner.sessions[1]["bars"]["SOXL"]["open"]
    runner._assess_control(
        1, state, {"SOXL": 0.1}, reason="executable_5pct_stop"
    )
    runner.sessions[1]["bars"]["SOXL"]["close"] *= 10
    runner.sessions[1]["market_regime"] = {"regime": "future-close-only"}
    runner._assess_control(
        1, state, {"SOXL": 0.1}, reason="executable_5pct_stop"
    )
    assert observed[0] == observed[1]
    assert observed[0][1] == runner.sessions[0]["market_regime"]

    runner._risk_engine.assess = lambda *_args, **_kwargs: RiskAction(
        action="approve", reason="shrink", budget_scalar=0.5
    )
    with pytest.raises(module.SoxlIsolatedResearchError, match="development_risk_rejected"):
        runner._assess_control(
            1, state, {"SOXL": 0.1}, reason="executable_5pct_stop"
        )


